package com.glomidco.utlx.engine.strategy.compiled

import com.glomidco.utlx.core.udm.UDM
import com.glomidco.utlx.core.udm.ScalarCanonical
import com.glomidco.utlx.core.udm.ExactArithmetic
import com.glomidco.utlx.core.interpreter.RuntimeError

/**
 * Runtime operations called by compiled bytecode.
 * These are the building blocks that generated code calls via INVOKESTATIC.
 * Each method takes UDM values and returns UDM values.
 */
@Suppress("unused") // Called from generated bytecode
object RuntimeOps {

    // ── Arithmetic ──

    /**
     * B35 Stage 2: `+`, `-` and `*` are exact when both operands carry an exact value.
     *
     * Delegates to the shared `ExactArithmetic` in `:core` rather than reimplementing the rule. The
     * interpreter calls the same function with the same fallback, which is the point: EB03 was what
     * happened when the two strategies each kept their own copy of a comparison rule and drifted
     * apart unnoticed, because the conformance suite exercises only the interpreted path.
     *
     * The Double value is still computed first and passed as the fallback, so operand coercion and
     * the string-concatenation branch behave exactly as before.
     */
    @JvmStatic
    fun add(left: UDM, right: UDM): UDM {
        val l = toNumber(left)
        val r = toNumber(right)
        if (l != null && r != null) {
            return UDM.Scalar(ExactArithmetic.add(rawNumber(left), rawNumber(right), l + r))
        }
        // String concatenation fallback
        return UDM.Scalar(toStringValue(left) + toStringValue(right))
    }

    @JvmStatic
    fun subtract(left: UDM, right: UDM): UDM {
        val fallback = (toNumber(left) ?: 0.0) - (toNumber(right) ?: 0.0)
        return UDM.Scalar(ExactArithmetic.subtract(rawNumber(left), rawNumber(right), fallback))
    }

    @JvmStatic
    fun multiply(left: UDM, right: UDM): UDM {
        val fallback = (toNumber(left) ?: 0.0) * (toNumber(right) ?: 0.0)
        return UDM.Scalar(ExactArithmetic.multiply(rawNumber(left), rawNumber(right), fallback))
    }

    // B35 Stage 2 stops here: divide and modulo stay on the Double path, because exact division
    // needs a digit count and a rounding mode that are a business decision. See ExactArithmetic.
    @JvmStatic
    fun divide(left: UDM, right: UDM): UDM {
        val r = toNumber(right) ?: 0.0
        if (r == 0.0) throw ArithmeticException("Division by zero")
        return UDM.Scalar((toNumber(left) ?: 0.0) / r)
    }

    @JvmStatic
    fun modulo(left: UDM, right: UDM): UDM {
        val r = toNumber(right) ?: 0.0
        if (r == 0.0) throw ArithmeticException("Modulo by zero")
        return UDM.Scalar((toNumber(left) ?: 0.0) % r)
    }

    // ── Comparison ──

    /**
     * EB03: equality **without coercion**, matching the interpreter.
     *
     * Equality used to be `compareValues(...) == 0`, and `compareValues` coerced through
     * `toNumber`, which also converts a numeric string and a boolean. So `"5" == 5` and `true == 1`
     * were **true** on the compiled path and **false** in the interpreter — the same transformation
     * giving different answers depending on which executable ran it, against the stated contract
     * that "a transformation that works in one executable works identically in all three". The
     * conformance suite never caught it because it drives the CLI, which interprets.
     *
     * The interpreter's semantics win: stricter, fail-closed, and already what the validation
     * functions assume — the string `"50"` is not the number 50. Numbers compare canonically, so
     * representation still does not matter; anything else compares without conversion.
     */
    @JvmStatic
    fun equal(left: UDM, right: UDM): UDM = UDM.Scalar(valuesEqual(left, right))

    @JvmStatic
    fun notEqual(left: UDM, right: UDM): UDM = UDM.Scalar(!valuesEqual(left, right))

    @JvmStatic
    fun greaterThan(left: UDM, right: UDM): UDM {
        return UDM.Scalar(orderOf(left, right) > 0)
    }

    @JvmStatic
    fun greaterEqual(left: UDM, right: UDM): UDM {
        return UDM.Scalar(orderOf(left, right) >= 0)
    }

    @JvmStatic
    fun lessThan(left: UDM, right: UDM): UDM {
        return UDM.Scalar(orderOf(left, right) < 0)
    }

    @JvmStatic
    fun lessEqual(left: UDM, right: UDM): UDM {
        return UDM.Scalar(orderOf(left, right) <= 0)
    }

    // ── Logical ──

    @JvmStatic
    fun isTruthy(value: UDM): Boolean {
        return when (value) {
            is UDM.Scalar -> {
                val v = value.value
                when (v) {
                    null -> false
                    is Boolean -> v
                    is Number -> v.toDouble() != 0.0
                    is String -> v.isNotEmpty()
                    else -> true
                }
            }
            is UDM.Array -> value.elements.isNotEmpty()
            is UDM.Object -> value.properties.isNotEmpty()
            else -> true
        }
    }

    @JvmStatic
    fun not(value: UDM): UDM = UDM.Scalar(!isTruthy(value))

    /**
     * B34: coerce a short-circuit result to a boolean, so `&&` / `||` return the same type here as
     * in the `:core` interpreter (`??` owns the default-value idiom; the logical operators do not
     * return their operand).
     */
    @JvmStatic
    fun toBoolean(value: UDM): UDM = UDM.Scalar(isTruthy(value))

    @JvmStatic
    fun negate(value: UDM): UDM = UDM.Scalar(-(toNumber(value) ?: 0.0))

    // ── Property access ──

    @JvmStatic
    fun getProperty(target: UDM, name: String): UDM {
        val value = when (target) {
            is UDM.Object -> target.properties[name] ?: UDM.Scalar.nullValue()
            else -> UDM.Scalar.nullValue()
        }
        // Unwrap XML text nodes: <Element>value</Element> is parsed as
        // UDM.Object({_text: Scalar(value)}). Unwrap to the scalar so
        // downstream stdlib functions receive the value directly —
        // same behavior as the interpreter's unwrapTextNode().
        return unwrapXmlTextNode(value)
    }

    /**
     * Unwrap XML text nodes. XML elements with only text content like
     * <Name>Alice</Name> are parsed as UDM.Object(properties={_text=Scalar("Alice")}).
     * This function extracts the scalar, matching the interpreter's behavior.
     */
    @JvmStatic
    fun unwrapXmlTextNode(value: UDM): UDM {
        if (value is UDM.Object && value.properties.size == 1 && value.properties.containsKey("_text")) {
            return value.properties["_text"] ?: value
        }
        return value
    }

    @JvmStatic
    fun getAttribute(target: UDM, name: String): UDM {
        return when (target) {
            is UDM.Object -> UDM.Scalar(target.attributes[name])
            else -> UDM.Scalar.nullValue()
        }
    }

    /**
     * EB09: `^metadata` access.
     *
     * `MemberAccess` carries an `isMetadata` flag for `^name`, and the interpreter reads it from
     * `UDM.Object.metadata`. `compileMemberAccess` had a branch for `isAttribute` and none for this,
     * so `$input.^schemaType` compiled as an ordinary property lookup and returned null — silently,
     * which is why it surfaced as a value difference rather than an error.
     *
     * Metadata is a string like an attribute, and read-only: `Property` has no metadata flag, so
     * there is no construction path to mirror.
     */
    @JvmStatic
    fun getMetadata(target: UDM, name: String): UDM {
        return when (target) {
            is UDM.Object -> target.getMetadata(name)?.let { UDM.Scalar.string(it) }
                ?: UDM.Scalar.nullValue()
            else -> UDM.Scalar.nullValue()
        }
    }

    @JvmStatic
    fun getIndex(target: UDM, index: Int): UDM = indexWithNumber(target, index)

    /**
     * EB07: index access with a **UDM** key, mirroring the interpreter.
     *
     * The previous signature took an `Int`, and `compileIndexAccess` reached it by calling
     * `asNumber()` on whatever the index expression produced — so a *string* key became `0.0`,
     * `byOrder["A"]` read element 0 of an object, and the answer was a silent null. The
     * group-then-look-up idiom was therefore wrong on the compiled path with no error at all:
     *
     * ```utlx
     * let byOrder = groupBy($input.lines, (l) -> l.oid)
     * map($input.orders, (o) -> byOrder[o.id] ?? [])      // always [] when compiled
     * ```
     *
     * A number indexes an array and a string indexes an object, and **out of bounds raises** rather
     * than yielding null, because that is what the interpreter does — returning null here made the
     * two strategies disagree on an error case as well as on a value.
     */
    @JvmStatic
    fun getIndexUdm(target: UDM, index: UDM): UDM {
        val key = (index as? UDM.Scalar)?.value
        return when (key) {
            is Number -> indexWithNumber(target, key.toInt())
            is String -> indexWithString(target, key)
            is Boolean -> indexWithString(target, key.toString())
            null -> throw RuntimeError("Index must be a number or string, got null")
            else -> throw RuntimeError("Index must be a number or string, got ${key::class.simpleName}")
        }
    }

    private fun indexWithNumber(target: UDM, index: Int): UDM {
        val elements = when (target) {
            is UDM.Array -> target.elements
            else -> throw RuntimeError("Cannot index non-array UDM type with number")
        }
        if (index < 0) throw RuntimeError("Array index out of bounds: negative index $index")
        if (index >= elements.size) {
            throw RuntimeError("Array index out of bounds: index $index, size ${elements.size}")
        }
        return elements[index]
    }

    private fun indexWithString(target: UDM, name: String): UDM {
        val obj = target as? UDM.Object
            ?: throw RuntimeError("Cannot index non-object UDM type with string")
        // Metadata and attributes are addressable through the same syntax, as in the interpreter.
        if (name.startsWith("^")) {
            val v = obj.getMetadata(name.substring(1)) ?: obj.getMetadata(name)
            return if (v != null) UDM.Scalar.string(v) else UDM.Scalar.nullValue()
        }
        if (name.startsWith("@")) {
            val v = obj.getAttribute(name.substring(1)) ?: obj.getAttribute(name)
            return if (v != null) UDM.Scalar.string(v) else UDM.Scalar.nullValue()
        }
        return obj.get(name) ?: UDM.Scalar.nullValue()
    }

    // ── Null coalescing ──

    @JvmStatic
    fun nullishCoalesce(left: UDM, right: UDM): UDM {
        return if (left is UDM.Scalar && left.value == null) right else left
    }

    // ── Object/Array construction ──

    @JvmStatic
    fun buildObject(keys: Array<String>, values: Array<UDM>): UDM {
        val props = LinkedHashMap<String, UDM>(keys.size)
        for (i in keys.indices) {
            props[keys[i]] = values[i]
        }
        return UDM.Object(props)
    }

    /**
     * EB08: build an object that distinguishes **XML attributes** from child properties.
     *
     * `@key:` in an object literal is marked `isAttribute` on the AST node, and the interpreter puts
     * those into `UDM.Object.attributes` while everything else becomes a property. The compiler
     * ignored the flag and passed every key to [buildObject], so an attribute came out as a child
     * element: `<Invoice number="…">` became `<Invoice><number>…</number>`.
     *
     * It is not only an XML concern, which is why it has to be the attribute map rather than a
     * naming convention — each serialiser re-presents attributes its own way:
     *
     * ```
     * xml    <Invoice number="INV-2025" count="42">
     * json   { "@number": "INV-2025", "@count": "42" }
     * yaml   '@number': INV-2025
     * ```
     *
     * Attributes are **strings** by construction, so the value is stringified here with the same
     * rules the interpreter uses — including that an integral number loses its decimal point, which
     * is why `@count: 42` shows up as `"42"` and not `42` even in JSON output.
     */
    @JvmStatic
    fun buildObjectWithAttributes(
        keys: Array<String>,
        values: Array<UDM>,
        attrKeys: Array<String>,
        attrValues: Array<UDM>
    ): UDM {
        val props = LinkedHashMap<String, UDM>(keys.size)
        for (i in keys.indices) {
            props[keys[i]] = values[i]
        }
        // No attributes means exactly the object buildObject would have made, so the common case
        // is unchanged.
        if (attrKeys.isEmpty()) return UDM.Object(props)
        val attrs = LinkedHashMap<String, String>(attrKeys.size)
        for (i in attrKeys.indices) {
            attrs[attrKeys[i]] = attributeText(attrValues[i])
        }
        return UDM.Object(props, attrs)
    }

    /**
     * An attribute's string form, mirroring the interpreter.
     *
     * Deliberately *not* routed through the exact-number rendering introduced for the numeric model:
     * the interpreter narrows to `Double` here, so matching it is what keeps the strategies in step.
     * That both of them stringify `100.10` as `100.1` is a separate gap, recorded in EB08.
     */
    private fun attributeText(v: UDM): String = when (v) {
        is UDM.Scalar -> when (val s = v.value) {
            null -> ""
            is Boolean -> s.toString()
            is Number -> {
                val d = s.toDouble()
                if (d == d.toLong().toDouble()) d.toLong().toString() else d.toString()
            }
            else -> s.toString()
        }
        else -> v.toString()
    }

    /**
     * Merge a spread object's properties into an existing map.
     * Used by compiled bytecode for { ...obj, key: value } expressions.
     */
    @JvmStatic
    fun spreadIntoObject(target: UDM, spread: UDM): UDM {
        if (target !is UDM.Object || spread !is UDM.Object) return target
        val merged = LinkedHashMap(target.properties)
        merged.putAll(spread.properties)
        return UDM.Object(
            merged,
            target.attributes + spread.attributes,
            target.name ?: spread.name,
            // EB09 family: metadata was being dropped here too, so a spread erased it.
            target.metadata + spread.metadata
        )
    }

    @JvmStatic
    fun buildArray(elements: Array<UDM>): UDM {
        return UDM.Array(elements.toList())
    }

    /**
     * EB11: append [spread]'s elements to [target], flattening — `[...arr, x]`.
     *
     * `compileArrayLiteral` compiled a `SpreadElement` as an ordinary element, so `[...arr]` came
     * out as `[[1, 2, 3]]` — a nested array instead of a flattened one.
     *
     * Spreading a non-array contributes **nothing**, which is what the interpreter does: it
     * evaluates the expression and silently ignores anything that is not an array. Mirrored rather
     * than improved, so the two strategies agree.
     */
    @JvmStatic
    fun spreadIntoArray(target: UDM, spread: UDM): UDM {
        val base = (target as? UDM.Array)?.elements ?: return target
        val extra = (spread as? UDM.Array)?.elements ?: return target
        return UDM.Array(base + extra)
    }

    // ── Lambda support ──

    /**
     * Invoke a UDM.Lambda with a list of arguments.
     * Used by compiled bytecode to call user-defined functions stored as local variables.
     */
    @JvmStatic
    fun invokeLambda(lambda: UDM, args: List<UDM>): UDM {
        if (lambda is UDM.Lambda) {
            return lambda.apply(args)
        }
        throw IllegalArgumentException("Expected Lambda, got ${lambda::class.simpleName}")
    }

    /**
     * Create a UDM.Lambda wrapping a static method in the generated class.
     * The method must have signature: static UDM methodName(List<UDM>, Map<String, UDM>)
     * Called by compiled bytecode to construct lambda values at runtime.
     *
     * EB05: [inputs] is the transformation's named-input map, **captured per construction**.
     * EB06: [captured] is the enclosing scope's bindings, snapshotted where the lambda value was
     * created — a lambda is a static method and cannot reach the enclosing frame's local slots.
     * A lambda body may reference an input (`$input.customers` inside a `map(...)` callback), and
     * the generated lambda is a *static* method with no access to `execute`'s locals. Threading the
     * map through as a second parameter keeps it per-invocation; a static field on the generated
     * class would have been simpler and would have raced between concurrent executions of the same
     * compiled transformation.
     */
    @JvmStatic
    fun makeLambda(
        clazz: Class<*>,
        methodName: String,
        inputs: Map<String, UDM>,
        captured: Map<String, UDM>
    ): UDM {
        val method = clazz.getMethod(methodName, List::class.java, Map::class.java, Map::class.java)
        return UDM.Lambda { args ->
            try {
                method.invoke(null, args, inputs, captured) as UDM
            } catch (e: java.lang.reflect.InvocationTargetException) {
                // Unwrap the reflection wrapper to expose the real error
                throw e.targetException
            }
        }
    }

    // ── Helpers ──

    private fun toNumber(udm: UDM): Double? {
        return when (udm) {
            is UDM.Scalar -> {
                when (val v = udm.value) {
                    is Number -> v.toDouble()
                    is String -> v.toDoubleOrNull()
                    is Boolean -> if (v) 1.0 else 0.0
                    else -> null
                }
            }
            else -> null
        }
    }

    private fun toStringValue(udm: UDM): String {
        return when (udm) {
            is UDM.Scalar -> udm.value?.toString() ?: "null"
            else -> udm.toString()
        }
    }

    /** The raw numeric value behind a scalar, with no coercion and no narrowing. */
    private fun rawNumber(udm: UDM): Number? = (udm as? UDM.Scalar)?.value as? Number

    /**
     * EB03 — equality, mirroring the interpreter's `valuesEqual`.
     *
     * B35: two numbers compare canonically, so a Long, a BigDecimal with trailing zeros and a
     * Double of the same quantity are one value, and two different integers above 2^53 are not.
     * Everything else compares by raw value with no conversion, and a non-scalar is never equal to
     * anything — both as the interpreter does it.
     */
    private fun valuesEqual(left: UDM, right: UDM): Boolean {
        if (left !is UDM.Scalar || right !is UDM.Scalar) return false
        val l = left.value
        val r = right.value
        if (l is Number && r is Number) return ScalarCanonical.numbersEqual(l, r)
        return l == r
    }

    /**
     * EB03 — ordering, mirroring the interpreter's `compareValues`.
     *
     * Numbers order exactly and strings order lexicographically. Anything else is an **error**
     * rather than a silent answer: the interpreter raises "Cannot compare these types", and the
     * compiled path used to coerce instead and return a verdict — so `"5" < 6` was `true` here and
     * a runtime error there. Returning a confident wrong answer is the worse of the two, especially
     * where the verdict gates whether a message is forwarded.
     */
    private fun orderOf(left: UDM, right: UDM): Int {
        val ln = rawNumber(left)
        val rn = rawNumber(right)
        if (ln != null && rn != null) return ScalarCanonical.compareNumbers(ln, rn)

        val ls = (left as? UDM.Scalar)?.value as? String
        val rs = (right as? UDM.Scalar)?.value as? String
        if (ls != null && rs != null) return ls.compareTo(rs)

        throw RuntimeError("Cannot compare these types")
    }
}
